export function getTechByCategory(category: TechCategory): TechRecommendation[] {
  return TECH_DATABASE.filter(t => t.category === category);
}

export function searchTech(query: string): TechRecommendation[] {
  const q = query.toLowerCase();
  return TECH_DATABASE.filter(t =>
    t.name.toLowerCase().includes(q) ||
    t.category.toLowerCase().includes(q) ||
    t.purpose.toLowerCase().includes(q) ||
    t.bestUseCase.toLowerCase().includes(q)
  );
}

export function getTechById(id: string): TechRecommendation | undefined {
  return TECH_DATABASE.find(t => t.id === id);
}
